// Rasterise web/public/brand/logo.svg into an N×N occupancy mask, grown by D cells,
// for the home masthead cloud (web/src/lib/logo-mask.mts). Rerun after changing the logo:
//   node tools/gen-logo-mask.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright';

const [svgPath = 'web/public/brand/logo.svg', out = 'web/src/lib/logo-mask.mts'] = process.argv.slice(2);
const N = 128,
  D = 0;
const svg = readFileSync(svgPath, 'utf8');
const b = await chromium.launch();
const p = await b.newPage();
const alpha = await p.evaluate(
  async ({ svg, N }) => {
    const img = new Image();
    img.src = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(svg)));
    await img.decode();
    const c = document.createElement('canvas');
    c.width = c.height = N * 4;
    const g = c.getContext('2d');
    g.drawImage(img, 0, 0, N * 4, N * 4);
    const d = g.getImageData(0, 0, N * 4, N * 4).data;
    const cells = [];
    for (let y = 0; y < N; y++)
      for (let x = 0; x < N; x++) {
        let on = 0;
        for (let dy = 0; dy < 4; dy++) for (let dx = 0; dx < 4; dx++) on ||= d[((y * 4 + dy) * N * 4 + x * 4 + dx) * 4 + 3] > 40;
        cells.push(on ? 1 : 0);
      }
    return cells;
  },
  { svg, N },
);
await b.close();
const at = (x, y) => x >= 0 && y >= 0 && x < N && y < N && alpha[y * N + x];
const rows = [];
for (let y = 0; y < N; y++) {
  let row = '';
  for (let x = 0; x < N; x++) {
    let on = false;
    for (let dy = -D; dy <= D && !on; dy++)
      for (let dx = -D; dx <= D && !on; dx++) on = dx * dx + dy * dy <= D * D + 1 && at(x + dx, y + dy);
    row += on ? '#' : '.';
  }
  rows.push(row);
}
writeFileSync(
  out,
  `// Generated by tools/gen-logo-mask.mjs from web/public/brand/logo.svg: the glyphs on a
// ${N}×${N} grid, grown by ${D} cells ('#' = ink), so the home masthead cloud keeps clear of the strokes only.
export const LOGO_MASK: readonly string[] = [
${rows.map((r) => `  '${r}',`).join('\n')}
];
`,
);
